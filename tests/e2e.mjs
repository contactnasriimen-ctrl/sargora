// Parcours complet : panier -> commande -> suivi -> admin -> livraison -> contact.  node _build/e2e.mjs <adminPassword>
import { createRequire } from 'module';
const require = createRequire('D:/Projects/_e2e-tools/package.json');
const puppeteer = require('puppeteer-core');
const BASE = 'http://localhost:8090';
const ADMIN_PASS = process.argv[2];
let ok = 0, fail = 0;
const check = (cond, label) => { if (cond) { ok++; console.log('  ✓ ' + label); } else { fail++; console.log('  ✗ ' + label); } };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('dialog', (d) => d.accept());
await page.setViewport({ width: 1366, height: 860 });
await page.evaluateOnNewDocument(() => { try { sessionStorage.setItem('sg-intro', '1'); } catch (e) {} });

console.log('Boutique');
await page.goto(BASE + '/boutique', { waitUntil: 'networkidle2' });
await page.click('.ptile [data-add-to-cart] button');
await page.waitForFunction(() => document.querySelector('[data-cart-count]').textContent.trim() === '1', { timeout: 8000 });
check(true, 'ajout rapide depuis la grille -> compteur = 1');
await page.type('[data-shop-search]', 'spotify');
await sleep(300);
const visible = await page.$$eval('[data-product]', (els) => els.filter((e) => !e.classList.contains('is-hidden')).map((e) => e.dataset.name));
check(visible.length === 1 && visible[0].includes('spotify'), 'recherche instantanée « spotify » -> 1 résultat');

console.log('Fiche produit');
await page.goto(BASE + '/produit/claude-pro', { waitUntil: 'networkidle2' });
await page.click('.opt:nth-of-type(2) .opt__box');
await sleep(200);
const price = await page.$eval('[data-buy-price]', (e) => e.textContent);
check(price.includes('195'), 'changement de formule -> prix 195 DT affiché (' + price + ')');
await page.click('.buy__add');
await page.waitForSelector('[data-drawer].is-open', { timeout: 8000 });
await page.waitForFunction(() => document.querySelectorAll('.ditem').length === 2, { timeout: 8000 });
check(true, 'tiroir panier ouvert avec 2 lignes');
await sleep(600);
await page.evaluate(() => document.querySelector('.ditem [data-q="1"]').click());
await page.waitForFunction(() => document.querySelector('[data-cart-count]').textContent.trim() === '3', { timeout: 8000 });
check(true, 'bouton + dans le tiroir -> 3 articles');

console.log('Commande');
await page.goto(BASE + '/commande', { waitUntil: 'networkidle2' });
await page.click('button[type=submit].btn--gold');
await page.waitForNavigation({ waitUntil: 'networkidle2' });
check(await page.$('.field__err') !== null, 'formulaire vide -> erreurs de validation');
await page.$eval('input[name=name]', (e) => (e.value = ''));
await page.type('input[name=name]', 'Client Test');
await page.$eval('input[name=email]', (e) => (e.value = ''));
await page.type('input[name=email]', 'client.test@example.com');
await page.$eval('input[name=phone]', (e) => (e.value = ''));
await page.type('input[name=phone]', '+216 22 333 444');
await page.click('.pay:nth-of-type(2) .pay__box');
await page.click('.terms__box');
await Promise.all([page.waitForNavigation({ waitUntil: 'networkidle2' }), page.click('button[type=submit].btn--gold')]);
const url = page.url();
check(/\/commande\/sg-/.test(url), 'commande créée -> page de confirmation (' + url.replace(BASE, '') + ')');
const ref = (await page.$eval('[data-copy-text]', (e) => e.textContent)).trim();
const body = await page.$eval('main', (e) => e.innerText);
check(body.includes('Flouci') && /Montant à régler/.test(body), 'instructions de paiement Flouci affichées');
check(await page.$eval('[data-cart-count]', (e) => e.textContent.trim()) === '0', 'panier vidé après commande');

console.log('Suivi');
const p2 = await browser.newPage();
await p2.goto(BASE + '/suivi', { waitUntil: 'networkidle2' });
await p2.type('input[name=ref]', ref);
await p2.type('input[name=email]', 'client.test@example.com');
await Promise.all([p2.waitForNavigation({ waitUntil: 'networkidle2' }), p2.click('button[type=submit]')]);
check(p2.url().includes('/commande/' + ref.toLowerCase()), 'suivi ref + e-mail -> page commande');
const ctx3 = await browser.createBrowserContext(); const p3 = await ctx3.newPage();
const r404 = await p3.goto(BASE + '/commande/' + ref.toLowerCase(), { waitUntil: 'networkidle2' });
check(r404.status() === 404, 'accès sans clé depuis une autre session -> 404');
await p3.close();

console.log('Admin');
{ const actx = await browser.createBrowserContext(); const ap = await actx.newPage(); await ap.setViewport({ width: 1366, height: 860 }); ap.on('dialog', (d) => d.accept()); ap.on('pageerror', (e) => errors.push(e.message)); globalThis.__ap = ap; }
const adminPage = globalThis.__ap;
await adminPage.goto(BASE + '/admin/connexion', { waitUntil: 'networkidle2' });
await adminPage.type('input[name=email]', 'admin@sargora.com');
await adminPage.type('input[name=password]', 'mauvais-mot-de-passe');
await Promise.all([adminPage.waitForNavigation({ waitUntil: 'domcontentloaded' }), adminPage.click('button[type=submit]')]);
check((await adminPage.content()).includes('incorrect'), 'mauvais mot de passe refusé');
await adminPage.type('input[name=password]', ADMIN_PASS);
await Promise.all([adminPage.waitForNavigation({ waitUntil: 'domcontentloaded' }), adminPage.click('button[type=submit]')]);
check(adminPage.url().endsWith('/admin'), 'connexion admin');
const kpi = await adminPage.$eval('.kpis', (e) => e.innerText);
check(/En attente de paiement\s*1/.test(kpi), 'tableau de bord : 1 commande en attente');
await adminPage.goto(BASE + '/admin/commandes', { waitUntil: 'networkidle2' });
await Promise.all([adminPage.waitForNavigation({ waitUntil: 'domcontentloaded' }), adminPage.click('.table tbody tr a')]);
await adminPage.click('.sp--green span');
await adminPage.type('textarea[name=delivery_info]', 'Claude Pro activé sur client.test@example.com jusqu’au 28/12.');
await Promise.all([adminPage.waitForNavigation({ waitUntil: 'domcontentloaded' }), adminPage.click('form.card button.b--gold')]);
check((await adminPage.content()).includes('Commande mise à jour'), 'statut -> Livrée + accès enregistrés');
await p2.reload({ waitUntil: 'networkidle2' });
const clientView = await p2.$eval('main', (e) => e.innerText);
check(clientView.includes('Claude Pro activé') && clientView.includes('livrée'), 'le client voit ses accès sur sa page');

await adminPage.goto(BASE + '/admin/produits/1', { waitUntil: 'networkidle2' });
await adminPage.$eval('textarea[name=options]', (e) => (e.value = '1 mois | 72\n3 mois | 199'));
await Promise.all([adminPage.waitForNavigation({ waitUntil: 'domcontentloaded' }), adminPage.click('.stackc button.b--gold')]);
check((await adminPage.content()).includes('Produit enregistré'), 'modification de prix enregistrée');
const pp = await browser.newPage();
await pp.goto(BASE + '/produit/chatgpt-plus', { waitUntil: 'networkidle2' });
check((await pp.$eval('[data-buy-price]', (e) => e.textContent)).includes('72'), 'nouveau prix visible sur le site');
await pp.$eval('textarea', () => 0).catch(() => 0);
await pp.close();
await adminPage.goto(BASE + '/admin/produits/1', { waitUntil: 'networkidle2' });
await adminPage.$eval('textarea[name=options]', (e) => (e.value = '1 mois | 69\n3 mois | 195\n12 mois | 749'));
await Promise.all([adminPage.waitForNavigation({ waitUntil: 'domcontentloaded' }), adminPage.click('.stackc button.b--gold')]);

console.log('Contact & newsletter');
await p2.goto(BASE + '/contact?service=branding', { waitUntil: 'networkidle2' });
check(await p2.$eval('input[value=branding]', (e) => e.checked), 'service pré-coché depuis ?service=branding');
await p2.type('input[name=name]', 'Sonia Test');
await p2.type('input[name=email]', 'sonia@example.com');
await p2.type('textarea[name=message]', 'Nous voulons refaire notre identité visuelle.');
await Promise.all([p2.waitForNavigation({ waitUntil: 'domcontentloaded' }), p2.click('.devis button[type=submit]')]);
check((await p2.content()).includes('Message'), 'demande de devis envoyée');
await p2.type('#news-email', 'news@example.com');
await p2.click('.news__btn');
await p2.waitForFunction(() => document.querySelector('[data-newsletter-msg]').textContent.length > 3, { timeout: 8000 });
check((await p2.$eval('[data-newsletter-msg]', (e) => e.textContent)).includes('Merci'), 'inscription newsletter');
await adminPage.goto(BASE + '/admin/messages', { waitUntil: 'networkidle2' });
check((await adminPage.content()).includes('Sonia Test'), 'la demande apparaît dans l’admin');

check(errors.length === 0, 'aucune erreur JavaScript' + (errors.length ? ' : ' + errors.join(' | ') : ''));
console.log(`\nRÉSULTAT : ${ok} réussis, ${fail} échecs`);
await browser.close();
process.exit(fail ? 1 : 0);
